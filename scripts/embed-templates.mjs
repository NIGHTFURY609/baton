// Embed templates/ in the bundle: `init` scaffolds from these strings because the plugin
// copy of baton has no templates/ folder (ADR 0017). Run by `npm run build`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const templatesDir = join(root, "templates");
const outFile = join(root, "src", "core", "templates.generated.ts");

/** POSIX paths relative to `dir`, files only, in plain `<` order. */
function walk(dir, prefix = "") {
  const out = [];
  for (const entry of readdirSync(join(dir, prefix), { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(dir, rel));
    else out.push(rel);
  }
  return out;
}

const keys = walk(templatesDir).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const lines = keys.map((key) => {
  const text = readFileSync(join(templatesDir, key), "utf8")
    .replace(/^﻿/, "")
    .replace(/\r\n?/g, "\n");
  return `  ${JSON.stringify(key)}: ${JSON.stringify(text)},`;
});

const source = [
  "// Generated by scripts/embed-templates.mjs from templates/. Do not edit: run `npm run embed:templates`.",
  "export const TEMPLATES: Readonly<Record<string, string>> = {",
  ...lines,
  "};",
  "",
].join("\n");

writeFileSync(outFile, source);
console.log(`embedded ${keys.length} template file(s) -> src/core/templates.generated.ts`);
